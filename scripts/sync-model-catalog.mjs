import { promises as fs } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { MODEL_CATALOG as currentCatalog } from "./model-catalog.mjs";

const projectRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const destination = path.join(projectRoot, "scripts", "model-catalog.mjs");
const repository = "mukowaty/firefox-translations";
const revision = "e43e74a227e023469fb1d1c0e560dd69c0408410";
const baseUrl = `https://huggingface.co/${repository}/resolve/${revision}`;
const pairs = [
  ["en", "ja"],
  ["ja", "en"],
  ["en", "ko"],
  ["ko", "en"],
  ["en", "zh-Hans"],
  ["zh-Hans", "en"],
  ["en", "zh-Hant"],
  ["zh-Hant", "en"],
  ["en", "de"],
  ["de", "en"],
  ["en", "es"],
  ["es", "en"],
  ["en", "fr"],
  ["fr", "en"],
  ["en", "pt"],
  ["pt", "en"],
  ["en", "ru"],
  ["ru", "en"],
  ["en", "it"],
  ["it", "en"],
];

function remoteLanguage(language) {
  if (language === "zh-Hans") return "zh";
  if (language === "zh-Hant") return "zh_hant";
  return language;
}

function filePart(fileName) {
  if (fileName.startsWith("model.")) return "model";
  if (fileName.startsWith("lex.")) return "lex";
  if (fileName.startsWith("srcvocab.")) return "srcvocab";
  if (fileName.startsWith("trgvocab.")) return "trgvocab";
  if (fileName.startsWith("vocab.")) return "vocab";
  throw new Error(`Unsupported model file: ${fileName}`);
}

async function fetchJson(url) {
  const response = await fetch(url, { headers: { Accept: "application/json" } });
  if (!response.ok) throw new Error(`${url}: HTTP ${response.status}`);
  return response.json();
}

const generated = {};
for (const [sourceLanguage, targetLanguage] of pairs) {
  const pairName = `${sourceLanguage}-${targetLanguage}`;
  const remotePair = `${remoteLanguage(sourceLanguage)}-${remoteLanguage(targetLanguage)}`;
  const endpoint =
    `https://huggingface.co/api/models/${repository}/tree/${revision}/${remotePair}` +
    "?recursive=true&expand=false";
  const entries = await fetchJson(endpoint);
  const files = {};
  for (const entry of entries.filter((item) => item.type === "file" && item.path.endsWith(".gz"))) {
    if (!entry.lfs?.oid || !Number.isSafeInteger(entry.size)) {
      throw new Error(`Missing LFS integrity metadata for ${entry.path}`);
    }
    const compressedName = entry.path.split("/").at(-1);
    const part = filePart(compressedName);
    files[part] = {
      fileName: compressedName.replace(/\.gz$/, ""),
      location: entry.path,
      size: entry.size,
      hash: entry.lfs.oid,
      compression: "gzip",
    };
  }
  if (!files.model || !files.lex || !(files.vocab || (files.srcvocab && files.trgvocab))) {
    throw new Error(`Incomplete model file set for ${pairName}`);
  }
  const previous = Object.values(currentCatalog).find(
    (model) =>
      model.sourceLanguage === sourceLanguage &&
      model.targetLanguage === targetLanguage,
  );
  generated[pairName] = {
    sourceLanguage,
    targetLanguage,
    version: previous?.version || "1",
    files,
  };
}

const output = `// Generated by scripts/sync-model-catalog.mjs.\n` +
  `export const MODEL_SOURCE = ${JSON.stringify({ repository, revision, baseUrl }, null, 2)};\n\n` +
  `export const MODEL_CATALOG = ${JSON.stringify(generated, null, 2)};\n`;
await fs.writeFile(destination, output, "utf8");
process.stdout.write(`Updated ${destination} with ${pairs.length} pinned model pairs.\n`);
